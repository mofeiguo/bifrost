// Package codex implements ChatGPT Plus/Pro Codex subscription as a Bifrost provider.
//
// The upstream is chatgpt.com's Codex Responses API, authenticated with the same
// ChatGPT OAuth tokens Codex CLI stores in ~/.codex/auth.json. Access tokens are
// refreshed via auth.openai.com and the rotated credential is written back through
// an optional KeyPersister.
package codex

import (
	"context"
	"strings"
	"time"

	"github.com/maximhq/bifrost/core/providers/openai"
	providerUtils "github.com/maximhq/bifrost/core/providers/utils"
	schemas "github.com/maximhq/bifrost/core/schemas"
	"github.com/valyala/fasthttp"
)

type codexProvider struct {
	logger              schemas.Logger
	client              *fasthttp.Client
	streamingClient     *fasthttp.Client
	exchangeClient      *fasthttp.Client
	networkConfig       schemas.NetworkConfig
	sendBackRawRequest  bool
	sendBackRawResponse bool
}

func NewCodexProvider(config *schemas.ProviderConfig, logger schemas.Logger) (*codexProvider, error) {
	config.CheckAndSetDefaults()

	requestTimeout := time.Second * time.Duration(config.NetworkConfig.DefaultRequestTimeoutInSeconds)
	client := &fasthttp.Client{
		ReadTimeout:         requestTimeout,
		WriteTimeout:        requestTimeout,
		MaxConnsPerHost:     config.NetworkConfig.MaxConnsPerHost,
		MaxIdleConnDuration: time.Second * time.Duration(config.NetworkConfig.KeepAliveTimeoutInSeconds),
		MaxConnWaitTimeout:  requestTimeout,
		MaxConnDuration:     time.Second * time.Duration(schemas.DefaultMaxConnDurationInSeconds),
		ConnPoolStrategy:    fasthttp.FIFO,
	}

	client = providerUtils.ConfigureProxy(client, config.ProxyConfig, logger)
	client = providerUtils.ConfigureDialer(client, config.NetworkConfig.AllowPrivateNetwork)
	client = providerUtils.ConfigureTLS(client, config.NetworkConfig, logger)
	streamingClient := providerUtils.BuildStreamingClient(client)

	exchangeClient := providerUtils.CloneFastHTTPClientConfig(client)
	exchangeClient.MaxResponseBodySize = maxExchangeBodyBytes
	exchangeClient.StreamResponseBody = false

	if config.NetworkConfig.BaseURL == "" {
		config.NetworkConfig.BaseURL = defaultCodexBaseURL
	}
	config.NetworkConfig.BaseURL = strings.TrimRight(config.NetworkConfig.BaseURL, "/")

	return &codexProvider{
		logger:              logger,
		client:              client,
		streamingClient:     streamingClient,
		exchangeClient:      exchangeClient,
		networkConfig:       config.NetworkConfig,
		sendBackRawRequest:  config.SendBackRawRequest,
		sendBackRawResponse: config.SendBackRawResponse,
	}, nil
}

func (p *codexProvider) GetProviderKey() schemas.ModelProvider {
	return schemas.Codex
}

func (p *codexProvider) creds(ctx *schemas.BifrostContext, key schemas.Key) (*codexCredentials, *schemas.BifrostError) {
	return resolveCredentials(ctx, key, p.exchangeClient, p.networkConfig.BaseURL, p.logger)
}

func (p *codexProvider) responsesURL(ctx *schemas.BifrostContext, creds *codexCredentials) string {
	return creds.BaseURL + providerUtils.GetPathFromContext(ctx, "/responses")
}

func (p *codexProvider) ListModels(ctx *schemas.BifrostContext, keys []schemas.Key, request *schemas.BifrostListModelsRequest) (*schemas.BifrostListModelsResponse, *schemas.BifrostError) {
	if len(keys) == 0 {
		return listModelsResponse(fallbackCodexModels), nil
	}
	creds, bErr := p.creds(ctx, keys[0])
	if bErr != nil {
		return nil, bErr
	}
	models, bErr := fetchCodexModels(ctx, p.client, creds)
	if bErr != nil {
		return nil, bErr
	}
	return listModelsResponse(models), nil
}

func (p *codexProvider) Responses(ctx *schemas.BifrostContext, key schemas.Key, request *schemas.BifrostResponsesRequest) (*schemas.BifrostResponsesResponse, *schemas.BifrostError) {
	creds, bErr := p.creds(ctx, key)
	if bErr != nil {
		return nil, bErr
	}
	return openai.HandleOpenAIResponsesRequest(
		ctx,
		p.client,
		p.responsesURL(ctx, creds),
		request,
		buildAuthHeaders(creds.Token, creds.AccountID),
		p.networkConfig.ExtraHeaders,
		providerUtils.ShouldSendBackRawRequest(ctx, p.sendBackRawRequest),
		providerUtils.ShouldSendBackRawResponse(ctx, p.sendBackRawResponse),
		p.GetProviderKey(),
		nil,
		parseCodexError,
		nil,
		p.logger,
	)
}

func (p *codexProvider) ResponsesStream(ctx *schemas.BifrostContext, postHookRunner schemas.PostHookRunner, postHookSpanFinalizer func(context.Context), key schemas.Key, request *schemas.BifrostResponsesRequest) (chan *schemas.BifrostStreamChunk, *schemas.BifrostError) {
	creds, bErr := p.creds(ctx, key)
	if bErr != nil {
		return nil, bErr
	}
	return openai.HandleOpenAIResponsesStreaming(
		ctx,
		p.streamingClient,
		p.responsesURL(ctx, creds),
		request,
		buildAuthHeaders(creds.Token, creds.AccountID),
		p.networkConfig.ExtraHeaders,
		p.networkConfig.StreamIdleTimeoutInSeconds,
		providerUtils.ShouldSendBackRawRequest(ctx, p.sendBackRawRequest),
		providerUtils.ShouldSendBackRawResponse(ctx, p.sendBackRawResponse),
		p.GetProviderKey(),
		postHookRunner,
		nil,
		parseCodexError,
		nil,
		nil,
		nil,
		p.logger,
		postHookSpanFinalizer,
	)
}

func (p *codexProvider) ChatCompletion(ctx *schemas.BifrostContext, key schemas.Key, request *schemas.BifrostChatRequest) (*schemas.BifrostChatResponse, *schemas.BifrostError) {
	if request == nil {
		return nil, configurationError("codex: chat request is required")
	}
	responses, bErr := p.Responses(ctx, key, request.ToResponsesRequest())
	if bErr != nil {
		return nil, bErr
	}
	return responses.ToBifrostChatResponse(), nil
}

func (p *codexProvider) ChatCompletionStream(ctx *schemas.BifrostContext, postHookRunner schemas.PostHookRunner, postHookSpanFinalizer func(context.Context), key schemas.Key, request *schemas.BifrostChatRequest) (chan *schemas.BifrostStreamChunk, *schemas.BifrostError) {
	if request == nil {
		return nil, configurationError("codex: chat request is required")
	}
	stream, bErr := p.ResponsesStream(ctx, postHookRunner, postHookSpanFinalizer, key, request.ToResponsesRequest())
	if bErr != nil {
		return nil, bErr
	}
	return convertResponsesStreamToChat(stream), nil
}

func convertResponsesStreamToChat(in chan *schemas.BifrostStreamChunk) chan *schemas.BifrostStreamChunk {
	out := make(chan *schemas.BifrostStreamChunk)
	go func() {
		defer close(out)
		for chunk := range in {
			if chunk != nil && chunk.BifrostResponsesStreamResponse != nil && chunk.BifrostChatResponse == nil {
				if converted := chunk.BifrostResponsesStreamResponse.ToBifrostChatResponse(); converted != nil {
					chunk.BifrostChatResponse = converted
					chunk.BifrostResponsesStreamResponse = nil
				}
			}
			out <- chunk
		}
	}()
	return out
}

